// Compiles docs/work/INDEX.md from frontmatter.
//
// Every work document in this repository already declares its edges —
// `related_adrs`, `related_tickets`, `governing_docs`, `affects`. Until this
// script existed, nothing read them: the graph was written down and never
// traversed. Asking "what did this ADR come from" meant grepping.
//
// The one thing here that cannot be got by reading a single file is the
// *inverted* edge. A ticket names its ADR; the ADR does not name the ticket.
// Backlinks are generated, never hand-written, so there is one source of truth.
//
// Reads frontmatter only, never body text. Output is sorted lexically
// throughout so it is deterministic — check-governance.js detects a stale index
// by rebuilding and comparing, which only works if the same input always
// renders the same bytes.

import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { parseFrontmatter, asList } from './frontmatter.js'

export const GENERATED_HEADER =
  '<!-- GENERATED by scripts/build-work-index.js — do not edit. Run `npm run index:work`. -->'

/** Directories walked, relative to the repository root. */
export const SOURCE_DIRS = ['docs/adr', 'docs/work/tickets', 'docs/work/specs', 'docs/work/runs', 'docs/work/handoffs']

/** Frontmatter fields that carry a path to another document. */
// `resolved_by` is deliberately absent: it names the commit that closed a
// ticket, not another document, so it is not a doc-to-doc edge.
// check-governance.js validates it separately.
export const REFERENCE_FIELDS = [
  'governing_docs', 'related_tickets', 'related_specs', 'related_adrs',
  'related_runs', 'supersedes', 'affects', 'parent_spec',
]

/** Never a document in its own right: generated output, and the blank template. */
const EXCLUDED = new Set(['docs/work/INDEX.md'])
const isTemplate = (path) => path.endsWith('/TEMPLATE.md')

const OPEN_TICKET = new Set(['open', 'in-progress'])

export function buildGraph(input) {
  const docs = input
    .filter((d) => !EXCLUDED.has(d.path) && !isTemplate(d.path))
    .sort((a, b) => a.path.localeCompare(b.path))

  const known = new Set(docs.map((d) => d.path))
  const backlinks = new Map()
  const dangling = []
  const hasOutbound = new Set()

  for (const d of docs) {
    for (const field of REFERENCE_FIELDS) {
      for (const to of asList(d.data?.[field])) {
        if (to === d.path) continue // self-reference is not an edge
        hasOutbound.add(d.path)
        if (!known.has(to)) {
          // A governing_docs entry may legitimately point at a standard or the
          // constitution, which are not work documents. Those are resolved by
          // check-governance.js against the filesystem; only references into
          // the work corpus are dangling here.
          if (isWorkPath(to)) dangling.push({ from: d.path, field, to })
          continue
        }
        if (!backlinks.has(to)) backlinks.set(to, [])
        backlinks.get(to).push({ from: d.path, field })
      }
    }
  }

  for (const list of backlinks.values()) {
    list.sort((a, b) => a.from.localeCompare(b.from) || a.field.localeCompare(b.field))
  }
  dangling.sort((a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to))

  const orphans = docs
    .filter((d) => !hasOutbound.has(d.path) && !backlinks.has(d.path))
    .map((d) => d.path)

  return { docs, backlinks, dangling, orphans }
}

function isWorkPath(p) {
  return SOURCE_DIRS.some((dir) => p.startsWith(`${dir}/`))
}

export function renderIndex(graph) {
  const { docs, backlinks, dangling, orphans } = graph
  const out = []

  out.push('---')
  out.push('title: Work Index')
  out.push('document_type: index')
  out.push('authority: descriptive')
  out.push('status: active')
  out.push('---')
  out.push('')
  out.push(GENERATED_HEADER)
  out.push('')
  out.push('# Work Index')
  out.push('')
  out.push('**Generated, and descriptive only.** `GOVERNANCE_INDEX.md` §9 applies: where this')
  out.push('disagrees with the documents it was built from, they are right and this is stale.')
  out.push('Regenerate with `npm run index:work`.')
  out.push('')

  out.push('## Open work')
  out.push('')
  const open = docs.filter((d) => d.data?.document_type === 'ticket' && OPEN_TICKET.has(d.data?.status))
  if (!open.length) {
    out.push('None.')
    out.push('')
  } else {
    const byClass = new Map()
    for (const d of open) {
      const cls = d.data.task_class || 'unclassified'
      if (!byClass.has(cls)) byClass.set(cls, [])
      byClass.get(cls).push(d)
    }
    for (const cls of [...byClass.keys()].sort()) {
      out.push(`### ${cls}`)
      out.push('')
      out.push('| Ticket | Status | Referenced by |')
      out.push('|---|---|---|')
      for (const d of byClass.get(cls)) {
        out.push(`| [${title(d)}](${up(d.path)}) | ${d.data.status} | ${refList(backlinks.get(d.path))} |`)
      }
      out.push('')
    }
  }

  out.push('## Decisions')
  out.push('')
  const adrs = docs.filter((d) => d.data?.document_type === 'adr')
  if (!adrs.length) {
    out.push('None.')
    out.push('')
  } else {
    out.push('Backlinks are generated. An ADR does not name the tickets it came from; this does.')
    out.push('')
    out.push('| ADR | Status | Implementation | Came from |')
    out.push('|---|---|---|---|')
    for (const d of adrs) {
      const impl = d.data.implementation_state || '—'
      out.push(`| [${title(d)}](${up(d.path)}) | ${d.data.status} | ${impl} | ${refList(backlinks.get(d.path))} |`)
    }
    out.push('')
  }

  out.push('## Runs')
  out.push('')
  const runs = docs
    .filter((d) => d.data?.document_type === 'run')
    .sort((a, b) => String(b.data.date || '').localeCompare(String(a.data.date || '')))
  if (!runs.length) {
    out.push('None.')
  } else {
    out.push('Newest first. `verdict` is what the gates said; `status` is where the run got to.')
    out.push('They are different facts and a run can carry a bad one of each.')
    out.push('')
    out.push('| Date | Run | Class | Status | Verdict |')
    out.push('|---|---|---|---|---|')
    for (const d of runs) {
      // An empty cell would read as "nothing to report". A missing verdict
      // means Verifier has not returned, which is a louder claim than that.
      const verdict = d.data.verdict ? d.data.verdict : '_no verdict yet_'
      out.push(`| ${d.data.date || '—'} | [${d.data.task || title(d)}](${up(d.path)}) | ` +
        `${d.data.task_class || '—'} | ${d.data.status || '—'} | ${verdict} |`)
    }
  }
  out.push('')

  out.push('## Orphans')
  out.push('')
  out.push('Referenced by nothing and referencing nothing. Usually a real defect —')
  out.push('either the document is stranded or an edge was never declared.')
  out.push('')
  if (!orphans.length) out.push('None.')
  else for (const p of orphans) out.push(`- [${p}](${up(p)})`)
  out.push('')

  out.push('## Dangling references')
  out.push('')
  out.push('A frontmatter field pointing at a work document that does not exist.')
  out.push('')
  if (!dangling.length) out.push('None.')
  else {
    out.push('| From | Field | Missing target |')
    out.push('|---|---|---|')
    for (const d of dangling) out.push(`| ${d.from} | \`${d.field}\` | ${d.to} |`)
  }
  out.push('')

  return out.join('\n')
}

const title = (d) => d.data?.title || d.path.split('/').pop().replace(/\.md$/, '')

/** Links are written from docs/work/INDEX.md, so every path needs `../` back to root. */
const up = (path) => `../../${path}`

function refList(refs) {
  if (!refs || !refs.length) return '—'
  return refs.map((r) => `[${r.from.split('/').pop().replace(/\.md$/, '')}](${up(r.from)})`).join(' · ')
}

export function readDocs(root) {
  const docs = []
  for (const dir of SOURCE_DIRS) {
    const abs = join(root, dir)
    let entries
    try { entries = walk(abs) } catch { continue }
    for (const file of entries) {
      const path = relative(root, file).split('\\').join('/')
      const { data, error } = parseFrontmatter(readFileSync(file, 'utf8'))
      docs.push({ path, data, error })
    }
  }
  return docs
}

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) out.push(...walk(full))
    else if (entry.endsWith('.md')) out.push(full)
  }
  return out
}

// --- CLI -------------------------------------------------------------------
// `npm run index:work`. Kept below the exports so the module stays importable
// and testable without writing anything to disk.

import { fileURLToPath } from 'node:url'
import { writeFileSync } from 'node:fs'

export const INDEX_PATH = 'docs/work/INDEX.md'

export function generate(root) {
  return renderIndex(buildGraph(readDocs(root)))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = process.cwd()
  const content = generate(root)
  writeFileSync(join(root, INDEX_PATH), content)
  console.log(`Wrote ${INDEX_PATH} (${content.split('\n').length} lines)`)
}
